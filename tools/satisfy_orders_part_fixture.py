"""Render the four verified original design-0 part records for a C probe."""

import json
from pathlib import Path

from tools.ne_layout import NE
from tools.satisfy_orders_design_cost_oracle import EXE, recover


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "tests/fixtures/satisfy_orders_design0_parts.h"


def render():
    oracle = recover()
    segment = bytes(NE(EXE).raw[1])
    rows = [oracle["hull"], *oracle["components"]]
    lengths = [143, 0x4E, 0x38, 0x3C]
    lines = ["/* Original STARS.EXE NE segment 2; generated by",
             " * tools/satisfy_orders_part_fixture.py. */",
             "#ifndef SATISFY_ORDERS_DESIGN0_PARTS_H",
             "#define SATISFY_ORDERS_DESIGN0_PARTS_H"]
    for index, (row, length) in enumerate(zip(rows, lengths)):
        data = segment[row["offset"]:row["offset"] + length]
        if len(data) != length:
            raise ValueError("part record truncated")
        if [int.from_bytes(data[0x2a + 2 * i:0x2c + 2 * i], "little")
                for i in range(4)] != row["base_cost"]:
            raise ValueError("part cost changed")
        lines.append("static const unsigned char original_part_%d[%d] = {" %
                     (index, length))
        for start in range(0, length, 12):
            lines.append("    " + ", ".join("0x%02x" % byte
                for byte in data[start:start + 12]) + ",")
        lines.append("};")
    lines.append("#endif")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    OUTPUT.write_text(render())
    print(json.dumps({"path": str(OUTPUT), "bytes": OUTPUT.stat().st_size}))
